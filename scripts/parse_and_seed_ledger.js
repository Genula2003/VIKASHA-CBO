function generateSql() {
  const accountSet = new Set();
  const consumers = [];

  for (const page of rawPages) {
    const lines = page.lines.trim().split('\n').map(l => l.trim()).filter(Boolean);
    for (const line of lines) {
      const match = line.match(/^(\d+)\s+([\d\.\/]+)\s+(.+)$/);
      if (!match) continue;

      const waterAcc = match[2];
      const remainder = match[3];

      const numMatch = remainder.match(/^(.+?)\s+(\d+)\s+(\d+)(?:\s+(.*))?$/);
      if (!numMatch) continue;

      const rawName = numMatch[1].trim();
      const prevReading = parseInt(numMatch[2], 10);
      const prevUnits = parseInt(numMatch[3], 10);
      const rawAddress = (numMatch[4] || '').trim();

      let accNum = waterAcc;
      if (accountSet.has(accNum)) {
        const areaCode = page.area.substring(0, 3).toUpperCase();
        accNum = `${areaCode}-${waterAcc}`;
      }
      accountSet.add(accNum);

      const address = rawAddress ? `${rawAddress} (${page.area})` : `${page.area}, MAGAMMANA`;

      consumers.push({
        accountNumber: accNum,
        name: rawName.replace(/'/g, "''"),
        address: address.replace(/'/g, "''"),
        area: page.area,
        prevReading,
        prevUnits
      });
    }
  }

  let sql = `-- ==============================================================================
-- 341 COMMUNITY CONSUMERS & MAY 2026 BASELINE METER READINGS
-- ==============================================================================

DO $$
DECLARE
    r_id UUID;
    c_id UUID;
BEGIN
    -- Get or create meter reader id
    SELECT id INTO r_id FROM public.profiles WHERE role = 'METER_READER' LIMIT 1;
    IF r_id IS NULL THEN
        r_id := 'b0eebc99-9c0b-4ef8-bb6d-6bb9bd380a22';
    END IF;

`;

  for (const c of consumers) {
    const prevCalc = Math.max(0, c.prevReading - c.prevUnits);
    sql += `    -- Consumer ${c.accountNumber}: ${c.name} (${c.area})
    INSERT INTO public.consumers (account_number, account_holder_name, address, status)
    VALUES ('${c.accountNumber}', '${c.name}', '${c.address}', 'ACTIVE')
    ON CONFLICT (account_number) DO UPDATE SET
        account_holder_name = EXCLUDED.account_holder_name,
        address = EXCLUDED.address,
        status = 'ACTIVE'
    RETURNING id INTO c_id;

    -- Baseline reading
    DELETE FROM public.meter_readings WHERE consumer_id = c_id;
    INSERT INTO public.meter_readings (consumer_id, reader_id, reading_date, previous_reading, current_reading, units_consumed, status)
    VALUES (c_id, r_id, '2026-04-30', ${prevCalc}, ${c.prevReading}, ${c.prevUnits}, 'VALID');

`;
  }

  sql += `END $$;\n`;

  fs.writeFileSync(path.join(__dirname, '../supabase/seed_consumers_ledger.sql'), sql);
  console.log(`Generated supabase/seed_consumers_ledger.sql with ${consumers.length} consumers!`);
  return consumers;
}

